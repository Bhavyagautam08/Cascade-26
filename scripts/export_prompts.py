"""Copy the language-model prompts and JSON schemas from the Python code into the app, byte for byte.

    cd backend
    uv run python ../scripts/export_prompts.py

Writes mobile/src/core/prompts.generated.ts. Never edit that file by hand: change the Python and re-run,
so the laptop and the phone always ask the model exactly the same thing.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app.perception import extractor  # noqa: E402

OUT = ROOT / "mobile" / "src" / "core" / "prompts.generated.ts"


def main():
    parts = {
        # str.format() placeholder {lexicon} kept as-is; doubled braces undone the way .format() would
        "EXTRACT_SYSTEM": extractor.SYSTEM.replace("{lexicon}", "\u0000LEX\u0000").replace("{{", "{").replace("}}", "}"),
        "EXTRACT_SCHEMA": json.dumps(extractor.LLMOutput.model_json_schema()),
    }
    lines = ["// GENERATED by scripts/export_prompts.py from the Python code. Do not edit: change the Python and re-run.", ""]
    lines.append(f"export const EXTRACT_SYSTEM_TEMPLATE = {json.dumps(parts['EXTRACT_SYSTEM'])};")
    lines.append("/** The system prompt with the lexicon filled in, exactly as extractor.py builds it. */")
    lines.append("export const extractSystem = (lexiconJson: string) => EXTRACT_SYSTEM_TEMPLATE.replace('\\u0000LEX\\u0000', lexiconJson);")
    lines.append(f"export const EXTRACT_SCHEMA = {json.dumps(parts['EXTRACT_SCHEMA'])};")
    lines.append("export const EXTRACT_OPTIONS = { temperature: 0, n_predict: 1024 }; // extractor.py: temperature 0, num_predict 1024")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
